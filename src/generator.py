"""Generate documentation updates from parsed source changes."""

from __future__ import annotations

from collections import defaultdict
from dataclasses import dataclass
from pathlib import PurePosixPath
from time import perf_counter
from typing import Iterable, Sequence

from .parser import ChangeRecord


@dataclass(frozen=True)
class DocumentationPatch:
    target: str
    title: str
    content: str


def _target_for_change(change: ChangeRecord, doc_root: str = "docs") -> str:
    lower = change.path.lower()

    if any(keyword in lower for keyword in ("openapi", "swagger", "api", "schema")):
        relative = PurePosixPath(doc_root) / "reference" / "api-reference.md"
    elif any(keyword in lower for keyword in ("release", "changelog", "version")):
        relative = PurePosixPath(doc_root) / "release-notes.md"
    elif any(keyword in lower for keyword in ("config", "env", "yaml", "yml", "docker", "helm")):
        relative = PurePosixPath(doc_root) / "configuration" / "deployment-config.md"
    else:
        relative = PurePosixPath(doc_root) / "generated" / "source-updates.md"

    return relative.as_posix()


def _render_section(change: ChangeRecord) -> str:
    return (
        f"### {change.path}\n"
        f"- Status: {change.status}\n"
        f"- Type: {change.change_type}\n"
        f"- Impact: {change.impact}\n"
        f"- Summary: {change.summary}\n"
    )


def generate_documentation_update(
    changes: Sequence[ChangeRecord],
    doc_root: str = "docs",
) -> list[DocumentationPatch]:
    """Generate grouped documentation patch files for the provided change list."""

    grouped: dict[str, list[ChangeRecord]] = defaultdict(list)
    for change in changes:
        grouped[_target_for_change(change, doc_root=doc_root)].append(change)

    patches: list[DocumentationPatch] = []
    for target, grouped_changes in sorted(grouped.items()):
        title = target.split("/")[-1].replace(".md", "").replace("-", " ").title()
        sections = "\n".join(_render_section(change) for change in grouped_changes)
        content = (
            "<!-- auto-generated by docs sync -->\n"
            f"# {title}\n\n"
            "## Summary\n"
            f"This update was generated from {len(grouped_changes)} change(s).\n\n"
            f"{sections}\n"
        )
        patches.append(DocumentationPatch(target=target, title=title, content=content))

    return patches


def render_pr_summary(changes: Iterable[ChangeRecord]) -> str:
    """Render a markdown summary suitable for a review workflow or PR discussion."""

    ordered = list(changes)
    if not ordered:
        return "No relevant source changes detected."

    lines = ["## Automated Documentation Sync Summary", ""]
    for change in ordered:
        lines.append(f"- **{change.path}** ({change.change_type}, {change.impact}): {change.summary}")

    return "\n".join(lines)


def run_sync_pipeline(changes: Sequence[ChangeRecord], max_latency_seconds: float = 1.0) -> dict:
    """Execute the main sync flow and report generation latency for a batch of changes."""

    start = perf_counter()
    patches = generate_documentation_update(changes)
    elapsed_ms = (perf_counter() - start) * 1000

    return {
        "generated_count": len(patches),
        "latency_ms": elapsed_ms,
        "patches": patches,
        "within_budget": elapsed_ms <= (max_latency_seconds * 1000),
    }
